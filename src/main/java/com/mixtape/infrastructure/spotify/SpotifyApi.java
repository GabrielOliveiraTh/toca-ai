package com.mixtape.infrastructure.spotify;

import com.mixtape.domain.error.BusinessRuleException;
import com.mixtape.infrastructure.http.Http;

import com.fasterxml.jackson.databind.JsonNode;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientResponseException;

@Component
class SpotifyApi {
    private static final String DEFAULT_BASE = "https://api.spotify.com/v1";

    private final RestClient api;
    private final SpotifyAuth auth;

    @Autowired
    SpotifyApi(SpotifyAuth auth, @Value("${spotify.api-base:" + DEFAULT_BASE + "}") String apiBase) {
        this.auth = auth;
        this.api = Http.client(apiBase);
    }

    JsonNode get(String uri, Object... vars) {
        try {
            return api.get().uri(uri, vars).header("Authorization", auth.bearer()).retrieve().body(JsonNode.class);
        } catch (RestClientResponseException e) {
            throw friendly(e, uri);
        }
    }

    JsonNode post(String uri, Object body, Object... vars) {
        try {
            return api.post().uri(uri, vars).header("Authorization", auth.bearer())
                    .contentType(MediaType.APPLICATION_JSON).body(body).retrieve().body(JsonNode.class);
        } catch (RestClientResponseException e) {
            throw apiException(e);
        }
    }

    JsonNode put(String uri, Object body, Object... vars) {
        try {
            return api.put().uri(uri, vars).header("Authorization", auth.bearer())
                    .contentType(MediaType.APPLICATION_JSON).body(body).retrieve().body(JsonNode.class);
        } catch (RestClientResponseException e) {
            throw apiException(e);
        }
    }

    private static SpotifyApiException apiException(RestClientResponseException e) {
        int status = e.getStatusCode().value();
        return new SpotifyApiException(status, "Spotify responded " + status + ": " + e.getResponseBodyAsString());
    }

    private static BusinessRuleException friendly(RestClientResponseException e, String uri) {
        int status = e.getStatusCode().value();
        boolean playlistRead = uri.startsWith("/playlists/");
        if (status == 403 && playlistRead) {
            return new BusinessRuleException(
                    "Spotify only releases the tracks of your own or collaborative playlists. "
                            + "Copy the playlist to your account or use the link of a Deezer playlist.");
        }
        if (status == 404 && playlistRead) {
            return new BusinessRuleException(
                    "Playlist not found on Spotify. Playlists generated by Spotify (Daily Mix, \"This Is…\", "
                            + "etc.) and private playlists of other people are not accessible.");
        }
        if (status == 401) {
            return new BusinessRuleException("Spotify session expired. Connect again.");
        }
        if (status == 429) {
            return new BusinessRuleException(
                    "Spotify limited the requests. Wait a moment and try again.");
        }
        return new BusinessRuleException("Spotify responded " + status + ": " + e.getResponseBodyAsString());
    }
}
