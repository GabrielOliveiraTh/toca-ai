package com.mixtape.infrastructure.youtube;

import com.mixtape.domain.error.BusinessRuleException;
import com.mixtape.infrastructure.http.Http;

import com.fasterxml.jackson.databind.JsonNode;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientResponseException;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

@Component
public class YoutubeClient {
    private static final Pattern LIST_ID = Pattern.compile("[?&]list=([A-Za-z0-9_-]+)");
    private static final Pattern NOISE = Pattern.compile(
            "(?i)\\b(official\\s*(music\\s*)?(video|audio|lyric\\s*video|visualizer)?|lyrics?|lyric\\s*video"
                    + "|video\\s*oficial|clipe\\s*oficial|áudio\\s*oficial|audio\\s*oficial|letra|legendado"
                    + "|tradução|hd|hq|4k|remastered(\\s*\\d{4})?|ao\\s*vivo)\\b");
    private static final int PAGE_SIZE = 50;
    private static final int PLAYLIST_PAGES = 4;

    record VideoTrack(String artist, String title) {
    }

    record PlaylistData(String name, List<VideoTrack> tracks) {
    }

    record PlaylistHit(String id, String title) {
    }

    private final String apiKey;
    private final RestClient http = Http.client("https://www.googleapis.com/youtube/v3");

    public YoutubeClient(@Value("${youtube.api-key:}") String apiKey) {
        this.apiKey = apiKey;
    }

    public boolean configured() {
        return apiKey != null && !apiKey.isBlank();
    }

    static boolean isYoutubeUrl(String text) {
        return text != null && (text.contains("youtube.com") || text.contains("youtu.be"));
    }

    static String playlistId(String url) {
        Matcher matcher = LIST_ID.matcher(url);
        if (!matcher.find()) {
            throw new BusinessRuleException(
                    "YouTube link without a playlist. Use the playlist link (youtube.com/playlist?list=…).");
        }
        return matcher.group(1);
    }

    private JsonNode get(String uri, Object... vars) {
        try {
            return http.get().uri(uri, vars).retrieve().body(JsonNode.class);
        } catch (RestClientResponseException e) {
            throw friendly(e);
        }
    }

    private static BusinessRuleException friendly(RestClientResponseException e) {
        int status = e.getStatusCode().value();
        String body = e.getResponseBodyAsString();
        if (status == 404 || body.contains("playlistNotFound")) {
            return new BusinessRuleException(
                    "YouTube playlist not found. It may be private or a mix generated by YouTube.");
        }
        if (body.contains("quotaExceeded")) {
            return new BusinessRuleException("The daily quota of the YouTube API is used up. Try again tomorrow.");
        }
        if (status == 400 || status == 403) {
            return new BusinessRuleException("The YouTube API key was rejected. Check YOUTUBE_API_KEY and that the "
                    + "YouTube Data API v3 is enabled.");
        }
        return new BusinessRuleException("YouTube responded " + status + ".");
    }

    PlaylistData readPlaylist(String id) {
        if (!configured()) {
            throw new BusinessRuleException(
                    "To use YouTube playlists, set the YOUTUBE_API_KEY key (see the README) and restart the app.");
        }
        JsonNode meta = get("/playlists?part=snippet&id={id}&key={k}", id, apiKey);
        if (meta == null || meta.path("items").isEmpty()) {
            throw new BusinessRuleException(
                    "YouTube playlist not found. It may be private or a mix generated by YouTube.");
        }
        String name = meta.path("items").path(0).path("snippet").path("title").asText("YouTube playlist");
        return new PlaylistData(name, items(id, PLAYLIST_PAGES));
    }

    List<VideoTrack> items(String id, int maxPages) {
        List<VideoTrack> out = new ArrayList<>();
        String pageToken = null;
        for (int page = 0; page < maxPages; page++) {
            JsonNode response = pageOfItems(id, pageToken);
            for (JsonNode item : response.path("items")) {
                JsonNode snippet = item.path("snippet");
                String title = snippet.path("title").asText("");
                boolean unavailable = title.equals("Private video") || title.equals("Deleted video") || title.isBlank();
                if (!unavailable) {
                    out.add(parse(title, snippet.path("videoOwnerChannelTitle").asText("")));
                }
            }
            pageToken = response.path("nextPageToken").asText(null);
            if (pageToken == null) {
                break;
            }
        }
        return out;
    }

    private JsonNode pageOfItems(String playlistId, String pageToken) {
        String base = "/playlistItems?part=snippet&maxResults=" + PAGE_SIZE + "&playlistId={id}&key={k}";
        if (pageToken == null) {
            return get(base, playlistId, apiKey);
        }
        return get(base + "&pageToken={p}", playlistId, apiKey, pageToken);
    }

    List<PlaylistHit> searchPlaylists(String query, int max) {
        if (!configured()) {
            return List.of();
        }
        List<PlaylistHit> out = new ArrayList<>();
        JsonNode response = get("/search?part=snippet&type=playlist&maxResults={m}&q={q}&key={k}", max, query, apiKey);
        if (response != null) {
            response.path("items").forEach(item -> out.add(new PlaylistHit(
                    item.path("id").path("playlistId").asText(),
                    item.path("snippet").path("title").asText(""))));
        }
        return out;
    }

    Map<String, Integer> itemCounts(List<String> ids) {
        Map<String, Integer> out = new LinkedHashMap<>();
        if (!configured() || ids.isEmpty()) {
            return out;
        }
        JsonNode response = get("/playlists?part=contentDetails&id={ids}&key={k}", String.join(",", ids), apiKey);
        if (response != null) {
            response.path("items").forEach(item ->
                    out.put(item.path("id").asText(), item.path("contentDetails").path("itemCount").asInt()));
        }
        return out;
    }

    static VideoTrack parse(String videoTitle, String channel) {
        String title = clean(videoTitle);
        String channelName = channel == null
                ? ""
                : channel.replaceAll("(?i)\\s*-\\s*topic$", "").replaceAll("(?i)vevo$", "").trim();
        boolean topicChannel = channel != null && channel.toLowerCase(Locale.ROOT).endsWith("- topic");

        int dash = title.indexOf(" - ");
        if (dash > 0) {
            String left = title.substring(0, dash).trim();
            String right = title.substring(dash + 3).trim();
            if (topicChannel && left.equalsIgnoreCase(channelName)) {
                return new VideoTrack(channelName, right);
            }
            return new VideoTrack(left, right);
        }
        return new VideoTrack(channelName, title);
    }

    private static String clean(String text) {
        String cleaned = text.replaceAll("\\([^)]*\\)|\\[[^]]*]", " ");
        cleaned = NOISE.matcher(cleaned).replaceAll(" ");
        cleaned = cleaned.replaceAll("(?i)\\b(ft|feat)\\.?\\s.*$", "");
        cleaned = cleaned.replaceAll("[|•·]+.*$", "");
        return cleaned.replaceAll("\\s{2,}", " ").replaceAll("^[\\s\\-–—]+|[\\s\\-–—]+$", "").trim();
    }
}
